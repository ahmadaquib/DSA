// Question 19
void printPattern19(int n)
{
    // Upper half
    for (int i = 0; i < n; i++)
    {
        // Stars
        for (int j = 1; j <= n - i; j++)
        {
            cout << "*";
        }

        // Spaces
        for (int j = 1; j <= 2 * i; j++)
        {
            cout << " ";
        }

        // Stars
        for (int j = 1; j <= n - i; j++)
        {
            cout << "*";
        }

        cout << endl;
    }

    // Lower half
    int iniS = 2 * n - 2;

    for (int i = 0; i < n; i++)
    {
        // Stars
        for (int j = 1; j <= i + 1; j++)
        {
            cout << "*";
        }

        // Spaces
        for (int j = 1; j <= iniS; j++)
        {
            cout << " ";
        }

        // Stars
        for (int j = 1; j <= i + 1; j++)
        {
            cout << "*";
        }

        iniS -= 2;

        cout << endl;
    }
}

// Question 20
void printPattern20(int n)
{
    int spaces = 2 * n - 2;
    for (int i = 1; i <= 2 * n - 1; i++)
    {
        int stars = i;
        if (i > n)
            stars = 2 * n - i;
        // stars
        for (int j = 1; j <= stars; j++)
        {
            cout << "*";
        }
        // spaces
        for (int j = 1; j <= spaces; j++)
        {
            cout << " ";
        }
        // stars
        for (int j = 1; j <= stars; j++)
        {
            cout << "*";
        }
        cout << endl;
        if (i < n)
            spaces -= 2;
        else
            spaces += 2;
    }
}

